// Unicode samples in this suite are intentional Czech font and extraction regressions.
import { expect, test } from '@playwright/test';
import { readFile, writeFile } from 'node:fs/promises';
import pixelmatch from 'pixelmatch';
import { PNG } from 'pngjs';
import type { RegisteredFont, RenderPDFResult } from '../../src/index';
import type { InspectedPage } from './pdf-inspector';

/** One browser-measured effect box and its authored physical PDF page. */
interface RasterRegion {
  /** Stable label for retained image and metric evidence. */
  id: string;
  /** Zero-based page index defined by the fixture's explicit break. */
  pageIndex: number;
  /** Root-relative bounds in CSS pixels, before page mapping. */
  x: number;
  y: number;
  width: number;
  height: number;
}

/** Copy an authored whole-pixel rectangle without alignment, fitting or blur.
 * @param image Browser screenshot or equal-scale PDF.js page bitmap.
 * @param x Left edge in CSS pixels.
 * @param y Top edge in CSS pixels.
 * @param width Rectangle width in CSS pixels.
 * @param height Rectangle height in CSS pixels.
 */
function crop(image: PNG, x: number, y: number, width: number, height: number): PNG {
  const result = new PNG({ width: Math.round(width), height: Math.round(height) });
  PNG.bitblt(image, result, Math.round(x), Math.round(y), result.width, result.height, 0, 0);
  return result;
}

/** Parse generated bytes through PDF.js in the same browser engine as the exporter.
 * @param page Live browser page that owns the PDF.js worker.
 * @param bytes Complete PDF serialized across the Playwright boundary.
 */
async function inspectPdf(
  page: import('@playwright/test').Page,
  bytes: number[],
): Promise<InspectedPage[]> {
  return page.evaluate(async (serializedBytes) => {
    // PDF.js is an independent development-only reader, never a conversion dependency.
    const inspectorPath = '/tests/browser/pdf-inspector.ts';
    const inspector = (await import(
      /* @vite-ignore */ inspectorPath
    )) as typeof import('./pdf-inspector');
    return inspector.inspectPdf(serializedBytes);
  }, bytes);
}

/** Normalize only whitespace that PDF.js may insert between positioned glyphs.
 * @param page Independently extracted text on one physical PDF page.
 */
function compactText(page: InspectedPage): string {
  return page.text
    .map((item) => item.text)
    .join('')
    .replace(/\s+/g, '');
}

test('public HTML export keeps exact Unicode text, two-page ownership and local rasters', async ({
  page,
  browser,
}, testInfo) => {
  test.setTimeout(120_000);
  await page.goto('/tests/fixtures/hybrid-pages.html');
  // The fixture supplies its own bounded CSS; test setup only adds synthetic content.
  const source = page.locator('#hybrid');
  const setup = await page.evaluate(async () => {
    // Vite resolves the same public source entry used by browser consumers.
    const modulePath = '/src/index.ts';
    const api = (await import(/* @vite-ignore */ modulePath)) as typeof import('../../src/index');
    // Both browser layout and the PDF writer receive these exact licensed font programs.
    const fonts = await Promise.all(
      (['Regular', 'Bold'] as const).map(async (face) => {
        const response = await fetch(`/fonts/NotoSans-${face}.ttf`);
        if (!response.ok) throw new Error(`Fixture font loading failed: ${face}`);
        return api.registerFont({
          family: 'Hybrid Sans',
          weight: face === 'Bold' ? 700 : 400,
          data: await response.arrayBuffer(),
        });
      }),
    );
    // Registered handles remain in the source document for the later public export.
    (window as unknown as { crossBrowserFonts: RegisteredFont[] }).crossBrowserFonts = fonts;
    const root = document.querySelector<HTMLElement>('#hybrid')!;
    root.innerHTML =
      '<h1>PAGEONE \u010d</h1>' +
      '<p>Native opening: selectable text.</p>' +
      '<div class="card"><p>RASTERONE Czech sample: \u00e1\u010d\u010f\u00e9\u011b\u00ed\u0148\u00f3\u0159\u0161\u0165\u00fa\u016f\u00fd\u017e.</p></div>' +
      '<p>Native text before the page break.</p>' +
      '<h2 class="break-before">PAGETWO \u017e</h2>' +
      '<div class="inset-card"><p>RASTERTWO follows the forced page break.</p></div>' +
      '<p>Native ending: second page text.</p>';
    await document.fonts.ready;
    // Browser geometry, rather than writer operations, fixes both local visual references.
    const origin = root.getBoundingClientRect();
    const breakBefore = root.querySelector<HTMLElement>('.break-before')!;
    const pageBreakY = breakBefore.getBoundingClientRect().top - origin.top;
    const selectors = [
      { id: 'gradient', pageIndex: 0, selector: '.card' },
      { id: 'inset', pageIndex: 1, selector: '.inset-card' },
    ] as const;
    const regions: RasterRegion[] = selectors.map(({ id, pageIndex, selector }) => {
      const bounds = root.querySelector<HTMLElement>(selector)!.getBoundingClientRect();
      return {
        id,
        pageIndex,
        x: bounds.left - origin.left,
        y: bounds.top - origin.top,
        width: bounds.width,
        height: bounds.height,
      };
    });
    return { markup: root.outerHTML, pageBreakY, regions };
  });
  // Capture the caller-owned DOM after setup, before the conversion starts.
  expect(await source.evaluate((element) => element.outerHTML)).toBe(setup.markup);
  const browserImage = PNG.sync.read(await source.screenshot());
  const evidence = await page.evaluate(async () => {
    const modulePath = '/src/index.ts';
    const api = (await import(/* @vite-ignore */ modulePath)) as typeof import('../../src/index');
    // One exactly fitting 460px source width leaves 20px margins on the 500px page.
    const result = await api.renderPDF(document.querySelector<HTMLElement>('#hybrid')!, {
      fonts: (window as unknown as { crossBrowserFonts: RegisteredFont[] }).crossBrowserFonts,
      format: { width: 500, height: 400 },
      margin: 20,
    });
    // Keep the completed public result so the real browser download reuses these exact bytes.
    (window as unknown as { crossBrowserResult: RenderPDFResult }).crossBrowserResult = result;
    return {
      bytes: Array.from(await result.toUint8Array()),
      pageCount: result.pageCount,
      warningCodes: result.warnings.map((warning) => warning.code),
    };
  });
  // Raw bytes and a small structural summary remain in the ignored Playwright output directory.
  await writeFile(testInfo.outputPath('cross-browser.pdf'), Buffer.from(evidence.bytes));
  expect(Buffer.from(evidence.bytes).subarray(0, 5).toString()).toBe('%PDF-');
  // A real Blob URL download must deliver the same immutable PDF in every tested engine.
  const downloadEvent = page.waitForEvent('download');
  await page.evaluate(async () => {
    await (
      window as unknown as { crossBrowserResult: RenderPDFResult }
    ).crossBrowserResult.download('cross-browser.pdf');
  });
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toBe('cross-browser.pdf');
  const downloadedPath = testInfo.outputPath('cross-browser-downloaded.pdf');
  await download.saveAs(downloadedPath);
  expect(await readFile(downloadedPath)).toEqual(Buffer.from(evidence.bytes));
  expect(evidence.pageCount).toBe(2);
  expect(evidence.warningCodes.filter((code) => code === 'RASTER_FALLBACK')).toHaveLength(2);
  expect(evidence.warningCodes).not.toContain('RASTER_TEXT_OMITTED');
  // PDF.js proves that the authored page break maps native and invisible text to distinct pages.
  const pages = await inspectPdf(page, evidence.bytes);
  expect(pages).toHaveLength(2);
  const firstText = compactText(pages[0]!);
  const secondText = compactText(pages[1]!);
  expect(firstText).toContain('PAGEONE\u010d');
  expect(firstText).toContain(
    'RASTERONECzechsample:\u00e1\u010d\u010f\u00e9\u011b\u00ed\u0148\u00f3\u0159\u0161\u0165\u00fa\u016f\u00fd\u017e.',
  );
  expect(firstText).not.toContain('PAGETWO');
  expect(secondText).toContain('PAGETWO\u017e');
  expect(secondText).toContain('RASTERTWO');
  expect(secondText).not.toContain('PAGEONE');
  expect(firstText.split('RASTERONE')).toHaveLength(2);
  expect(secondText.split('RASTERTWO')).toHaveLength(2);
  for (const output of pages) {
    // Each page holds one selected local effect, not a full-page flattened bitmap.
    expect(output.width).toBe(500);
    expect(output.height).toBe(400);
    expect(output.imagePaints).toBe(1);
    expect(output.imageSizes).toHaveLength(1);
    expect(output.imageSizes[0]!.width).toBeGreaterThan(0);
    expect(output.imageSizes[0]!.width).toBeLessThan(1000);
    expect(output.imageSizes[0]!.height).toBeGreaterThan(0);
    expect(output.imageSizes[0]!.height).toBeLessThan(800);
  }
  // PDF.js and the source screenshot use one physical pixel per CSS pixel in this browser.
  const pdfImages = pages.map((output) =>
    PNG.sync.read(Buffer.from(output.png.split(',')[1]!, 'base64')),
  );
  const visual = await Promise.all(
    setup.regions.map(async (region) => {
      // The authored break places its following heading at the top of page two's content box.
      const pageY = region.y - (region.pageIndex === 1 ? setup.pageBreakY : 0);
      const reference = crop(browserImage, region.x, region.y, region.width, region.height);
      const actual = crop(
        pdfImages[region.pageIndex]!,
        20 + region.x,
        20 + pageY,
        region.width,
        region.height,
      );
      const differenceImage = new PNG({ width: reference.width, height: reference.height });
      // The existing hybrid visual gate excludes antialiased edges without moving either image.
      const differentPixels = pixelmatch(
        reference.data,
        actual.data,
        differenceImage.data,
        reference.width,
        reference.height,
        { threshold: 0.1, includeAA: false },
      );
      const ratio = differentPixels / (reference.width * reference.height);
      await Promise.all([
        writeFile(testInfo.outputPath(`${region.id}-browser.png`), PNG.sync.write(reference)),
        writeFile(testInfo.outputPath(`${region.id}-pdf.png`), PNG.sync.write(actual)),
        writeFile(
          testInfo.outputPath(`${region.id}-difference.png`),
          PNG.sync.write(differenceImage),
        ),
      ]);
      return { id: region.id, pageIndex: region.pageIndex, pageY, differentPixels, ratio };
    }),
  );
  // Save measured outcomes before the visual gate so failures remain auditable.
  await writeFile(
    testInfo.outputPath('cross-browser-visual.json'),
    JSON.stringify({ pageBreakY: setup.pageBreakY, regions: setup.regions, visual }, null, 2),
  );
  for (const region of visual) {
    expect(region.ratio, `${region.id}: browser/PDF local raster pixels`).toBeLessThan(0.05);
  }
  await writeFile(
    testInfo.outputPath('cross-browser-structure.json'),
    JSON.stringify(
      {
        project: testInfo.project.name,
        browserEngine: browser.browserType().name(),
        browserVersion: browser.version(),
        pageCount: evidence.pageCount,
        warningCodes: evidence.warningCodes,
        pages: pages.map((output) => ({
          width: output.width,
          height: output.height,
          text: output.text.map((item) => item.text),
          imagePaints: output.imagePaints,
          imageSizes: output.imageSizes,
        })),
      },
      null,
      2,
    ),
  );
  expect(await source.evaluate((element) => element.outerHTML)).toBe(setup.markup);
});

test('renderHTML releases its isolated document and preserves the caller page', async ({
  page,
}) => {
  test.setTimeout(120_000);
  await page.goto('/tests/fixtures/hybrid-pages.html');
  const evidence = await page.evaluate(async () => {
    const modulePath = '/src/index.ts';
    const api = (await import(/* @vite-ignore */ modulePath)) as typeof import('../../src/index');
    // The isolated iframe must register the very same bytes as its PDF output.
    const response = await fetch('/fonts/NotoSans-Regular.ttf');
    if (!response.ok) throw new Error('Fixture font loading failed.');
    const fontBytes = await response.arrayBuffer();
    const sourceMarkup = document.querySelector<HTMLElement>('#hybrid')!.outerHTML;
    const iframeCount = document.querySelectorAll('iframe').length;
    const result = await api.renderHTML(
      '<!doctype html><html><head><style>body{margin:0;width:460px;font:16px/24px "Cross Browser Sans"}</style></head><body><p>ISOLATEDCOPY \u010c\u0161\u017e \u00e1\u010f\u016f.</p></body></html>',
      {
        isolation: 'iframe',
        fonts: [{ family: 'Cross Browser Sans', data: fontBytes }],
        sourceWidth: 460,
        format: { width: 500, height: 400 },
        margin: 20,
      },
    );
    return {
      bytes: Array.from(await result.toUint8Array()),
      pageCount: result.pageCount,
      beforeFrames: iframeCount,
      afterFrames: document.querySelectorAll('iframe').length,
      sourceBefore: sourceMarkup,
      sourceAfter: document.querySelector<HTMLElement>('#hybrid')!.outerHTML,
    };
  });
  expect(evidence.pageCount).toBe(1);
  expect(evidence.afterFrames).toBe(evidence.beforeFrames);
  expect(evidence.sourceAfter).toBe(evidence.sourceBefore);
  const pages = await inspectPdf(page, evidence.bytes);
  expect(pages).toHaveLength(1);
  expect(compactText(pages[0]!)).toContain('ISOLATEDCOPY\u010c\u0161\u017e\u00e1\u010f\u016f.');
  expect(pages[0]!.imagePaints).toBe(0);
});

test('WebKit rejects a blurred inset shadow that its SVG image cannot paint', async ({
  page,
  browser,
}) => {
  test.skip(browser.browserType().name() !== 'webkit');
  await page.goto('/tests/fixtures/hybrid-pages.html');
  const evidence = await page.evaluate(async () => {
    const modulePath = '/src/index.ts';
    const api = (await import(/* @vite-ignore */ modulePath)) as typeof import('../../src/index');
    const response = await fetch('/fonts/NotoSans-Regular.ttf');
    if (!response.ok) throw new Error('Fixture font loading failed.');
    const font = await api.registerFont({
      family: 'Hybrid Sans',
      data: await response.arrayBuffer(),
    });
    const root = document.querySelector<HTMLElement>('#hybrid')!;
    root.innerHTML =
      '<div class="inset-card" style="box-shadow: inset 0 0 12px #78869c">BLURREDINSET</div>';
    await document.fonts.ready;
    const markup = root.outerHTML;
    try {
      await api.renderPDF(root, { fonts: [font], format: { width: 500, height: 400 }, margin: 20 });
      return { code: 'UNEXPECTED_SUCCESS', sourceUnchanged: root.outerHTML === markup };
    } catch (error) {
      return {
        code: error instanceof api.RenderPDFError ? error.code : 'UNEXPECTED_ERROR',
        sourceUnchanged: root.outerHTML === markup,
      };
    }
  });
  expect(evidence.code).toBe('RASTER_FAILED');
  expect(evidence.sourceUnchanged).toBe(true);
});

